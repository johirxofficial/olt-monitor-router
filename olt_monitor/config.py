def load_config(path: str | Path | None = None) -> dict:
    """Load and return the full configuration dictionary."""
    load_dotenv()
    cfg_path = Path(path) if path else (ROOT / "config" / "config.yaml")
    if not cfg_path.is_absolute():
        cfg_path = ROOT / cfg_path
    if not cfg_path.exists() and path is None:
        # a freshly unpacked source bundle ships only the template
        example = ROOT / "config" / "config.example.yaml"
        if example.exists():
            cfg_path = example
    if not cfg_path.exists():
        raise FileNotFoundError(f"config file not found: {cfg_path}")

    with cfg_path.open("r", encoding="utf-8") as fh:
        raw = yaml.safe_load(fh) or {}

    cfg = _expand(raw)

    cfg.setdefault("app", {})
    cfg["app"].setdefault("title", "OLT + Router Monitor")
    cfg["app"].setdefault("host", "0.0.0.0")
    cfg["app"].setdefault("port", 8000)
    cfg["app"].setdefault("timezone", "Asia/Dhaka")
    cfg["app"].setdefault("log_level", "INFO")
    cfg["app"].setdefault("refresh_seconds", 120)

    cfg.setdefault("database", {})
    database = cfg["database"]
    # ---- MySQL connection ------------------------------------------------
    # The values may reference ${DB_*} in config.yaml; .env supplies them.
    database.setdefault("host", "127.0.0.1")
    database.setdefault("port", 3306)
    database.setdefault("name", "olt_monitor")
    database.setdefault("user", "olt_monitor")
    database.setdefault("password", "")
    database.setdefault("charset", "utf8mb4")
    # ---- retention -------------------------------------------------------
    # 1 day = keep exactly the last 24 hours; a dedicated maintenance thread
    # prunes every few minutes so the history tables (and their indexes) stay
    # small and the web pages stay fast.
    database.setdefault("keep_history_days", 1)
    database.setdefault("prune_interval_seconds", 300)
    database.setdefault("history_every_n_polls", 5)
    # local scratch directory: encryption key + per-OLT forwarding-table cache.
    # No measurement is stored in this file any more - everything is in MySQL.
    database.setdefault("path", "data/olt_monitor.db")

    cfg.setdefault("polling", {})
    # Every device is polled on the same 10-minute cycle.  Routers used to run
    # every 30-120 s, which meant a slow RouterOS dump (2-3 min on a busy box)
    # kept a poller running almost continuously and starved the web UI.  The
    # manual "Poll all now" button is the on-demand path.
    cfg["polling"].setdefault("olt_interval_seconds", 600)
    cfg["polling"].setdefault("router_interval_seconds", 600)
    cfg["polling"].setdefault("snmp_max_repetitions", 25)

    cfg.setdefault("alerts", {})
    cfg.setdefault("correlate", {})

    cfg["_root"] = str(ROOT)
    cfg["_config_path"] = str(cfg_path)
    return cfg


def db_path(cfg: dict) -> Path:
    """Absolute path of the local runtime anchor (``data/``).

    All measurements live in MySQL now.  This path is only used as the anchor
    for local files that must travel with the installation: the encryption key
    (``data/.secret_key``) and the per-OLT forwarding-table cache
    (``data/fdb_*.json``).  The parent directory is created on demand.
    """
    raw = str(dig(cfg, "database.path", "data/olt_monitor.db"))
    path = Path(raw)
    if not path.is_absolute():
        path = ROOT / path
    path.parent.mkdir(parents=True, exist_ok=True)
    return path
