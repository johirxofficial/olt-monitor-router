def dig(mapping: Any, path: str, default: Any = None) -> Any:
    """Return ``mapping["a"]["b"]`` for ``path="a.b"``, or *default*."""
    node = mapping
    for part in path.split("."):
        if isinstance(node, dict) and part in node:
            node = node[part]
        else:
            return default
    return node


def _merge_tables(base: dict[str, Any], extra: dict[str, Any]) -> dict[str, Any]:
    """Merge ``onu_tables`` style dicts one level deep."""
    merged = {k: (dict(v) if isinstance(v, dict) else v) for k, v in base.items()}
    for key, value in (extra or {}).items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = {**merged[key], **value}
        else:
            merged[key] = value
    return merged


def normalise_olt(entry: dict[str, Any], index: int) -> dict[str, Any]:
    olt = {**DEFAULT_OLT, **(entry or {})}
    olt.setdefault("name", f"OLT-{index + 1}")
    olt["name"] = str(olt["name"])

    # ---- vendor / PON architecture ---------------------------------
    brand = str(olt.get("brand") or "auto").strip().lower()
    if brand not in vendors.PROFILES:
        brand = "auto"
    profile = vendors.profile("generic" if brand == "auto" else brand)
    pon_type = str(olt.get("pon_type") or "").strip().lower()
    if pon_type not in vendors.PON_TYPES:
        pon_type = str(profile.get("pon_type") or "epon")
    olt["brand"] = brand
    olt["pon_type"] = pon_type
    olt["brand_label"] = vendors.brand_label("auto" if brand == "auto" else brand)

    # a per-device classify block wins over the vendor default, and both accept
    # either a single regex string or a list of them
    profile_classify = vendors.classify_for("generic" if brand == "auto" else brand, pon_type)
    olt["classify"] = {**profile_classify, **(olt.get("classify") or {})}

    # ---- capacity / Telnet profile ---------------------------------
    try:
        configured = int(olt.get("max_onus_per_pon") or 0)
    except (TypeError, ValueError):
        configured = 0
    olt["max_onus_per_pon"] = configured or int(
        vendors.pon_defaults(pon_type).get("default_max_onus") or 64
    )
    if not olt.get("telnet_profile"):
        olt["telnet_profile"] = str(profile.get("telnet_profile") or "epon_vsol")

    olt["oids"] = {**DEFAULT_OIDS, **(olt.get("oids") or {})}
    onu_profile = ONU_TABLE_PROFILES.get((brand, pon_type)) or {}
    onu_tables = _merge_tables(DEFAULT_ONU_TABLES, onu_profile)
    olt["onu_tables"] = _merge_tables(onu_tables, olt.get("onu_tables") or {})
    mac_profile = MAC_TABLE_PROFILES.get((brand, pon_type)) or {}
    olt["mac_table"] = {
        **DEFAULT_MAC_TABLE,
        **mac_profile,
        **(olt.get("mac_table") or {}),
    }
    return olt


def normalise_router(entry: dict[str, Any], index: int) -> dict[str, Any]:
    router = {**DEFAULT_ROUTER, **(entry or {})}
    router.setdefault("name", f"MikroTik-{index + 1}")
    router["name"] = str(router["name"])
    return router


def device_lists(cfg: dict) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Return ``(olts, routers)`` for either config shape (config.yaml only).

    Used to *seed* the device registry and by the CLI tools.  The web UI and
    the polling engine read the registry instead - see ``olt_monitor.registry``.
    """
    raw_olts = cfg.get("olts")
    if isinstance(raw_olts, list) and raw_olts:
        defaults = dict(cfg.get("olt_defaults") or {})
        olts = [
            normalise_olt({**defaults, **(entry or {})}, i)
            for i, entry in enumerate(raw_olts)
        ]
    else:
        single = dict(cfg.get("olt") or {})
        olts = [normalise_olt(single, 0)] if single else []

    raw_routers = cfg.get("routers")
    if isinstance(raw_routers, list) and raw_routers:
        defaults = dict(cfg.get("router_defaults") or {})
        routers = [
            normalise_router({**defaults, **(entry or {})}, i)
            for i, entry in enumerate(raw_routers)
        ]
    else:
        single = dict(cfg.get("router") or {})
        routers = [normalise_router(single, 0)] if single else []

    apply_optical_file(olts)
    return olts, routers


def raw_device_entries(cfg: dict) -> list[tuple[str, dict[str, Any]]]:
    """Return ``[(kind, raw_entry), ...]`` exactly as written in config.yaml.

    This is what seeds the registry, so a device keeps only the keys the user
    actually wrote (defaults are re-applied from code on every read).
    """
    entries: list[tuple[str, dict[str, Any]]] = []

    raw_olts = cfg.get("olts")
    if isinstance(raw_olts, list) and raw_olts:
        defaults = dict(cfg.get("olt_defaults") or {})
        entries += [("olt", {**defaults, **(e or {})}) for e in raw_olts]
    elif isinstance(cfg.get("olt"), dict) and cfg["olt"]:
        entries.append(("olt", dict(cfg["olt"])))

    raw_routers = cfg.get("routers")
    if isinstance(raw_routers, list) and raw_routers:
        defaults = dict(cfg.get("router_defaults") or {})
        entries += [("router", {**defaults, **(e or {})}) for e in raw_routers]
    elif isinstance(cfg.get("router"), dict) and cfg["router"]:
        entries.append(("router", dict(cfg["router"])))

    return entries


_OPTICAL_CACHE: dict[str, tuple[float, dict[str, Any]]] = {}


def _optical_file_data(path: Path) -> dict[str, Any]:
    """Read ``config/optical_oids.yaml``, cached until its mtime changes."""
    try:
        mtime = path.stat().st_mtime
    except OSError:
        return {}
    cached = _OPTICAL_CACHE.get(str(path))
    if cached and cached[0] == mtime:
        return cached[1]
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except Exception:
        return {}
    if not isinstance(data, dict):
        return {}
    _OPTICAL_CACHE[str(path)] = (mtime, data)
    return data


def apply_optical_file(olts: list[dict[str, Any]]) -> None:
    """Merge ``config/optical_oids.yaml`` (written by discover_olt.py)."""
    path = ROOT / OPTICAL_FILE
    if not path.exists() or not olts:
        return
    data = _optical_file_data(path)
    if not data:
        return

    profiles = data.get("_profiles") or {}
    legacy_epon = data.get("_default") or {}
    for olt in olts:
        brand = str(olt.get("brand") or "auto").lower()
        pon_type = str(olt.get("pon_type") or "").lower()
        extra: dict[str, Any] = {}
        # A ``_default`` block written by the old discovery tool describes
        # VSOL/ECOM EPON hardware.  Applying it to a GPON OLT made every
        # optical walk look at the wrong enterprise tree, and applying it to a
        # BDCOM EPON produced the "optical OIDs are set but no rows matched"
        # warning.  Only explicitly configured VSOL/ECOM EPON devices inherit
        # the legacy block; auto-detected devices use the built-in profile for
        # the brand the collector actually finds.
        if pon_type == "epon" and brand in ("vsol", "ecom"):
            extra = _merge_tables(extra, legacy_epon)
        for key in (f"{brand}:{pon_type}", f"*:{pon_type}", f"{brand}:*"):
            block = profiles.get(key) if isinstance(profiles, dict) else None
            if isinstance(block, dict):
                extra = _merge_tables(extra, block)
        per_device = data.get(olt.get("name")) or {}
        if not isinstance(per_device, dict):
            per_device = {}
        extra = _merge_tables(extra, per_device)
        if extra:
            olt["onu_tables"] = _merge_tables(olt.get("onu_tables") or {}, extra)


