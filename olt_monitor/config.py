"""Configuration loading and device normalisation.

Reads ``config/config.yaml``, expands ``${ENV_VAR}`` and ``${ENV_VAR:default}``
references from the environment (and from a ``.env`` file), then normalises the
device list.

Two config shapes are accepted, so an existing single-device file keeps working
untouched::

    # single device (original layout)
    olt:
      host: 192.0.2.10
      community: public
    router:
      host: 198.51.100.1
      api_port: 8728

    # many devices
    olts:
      - name: OLT-1
        host: 192.0.2.10
    olts:
      - name: OLT-2
        host: 192.0.2.11
    routers:
      - name: MikroTik-1
        host: 198.51.100.1

Optical OIDs (which are firmware specific) are merged in from the optional,
auto-generated ``config/optical_oids.yaml`` file, so the hand-written
``config.yaml`` never has to be rewritten by a tool.
"""

